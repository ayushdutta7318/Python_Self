# Datatypes in Python:

"""
| Data Type  | Example            | Used for                      |
| ---------- | ------------------ | ----------------------------- |
| `int`      | `25`               | Whole numbers                 |
| `float`    | `25.5`             | Decimal numbers               |
| `complex`  | `3 + 4j`           | Complex numbers               |
| `str`      | `"Python"`         | Text                          |
| `bool`     | `True` / `False`   | True/false values             |
| `list`     | `[10, 20, 30]`     | Ordered collection            |
| `tuple`    | `(10, 20, 30)`     | Ordered, immutable collection |
| `set`      | `{10, 20, 30}`     | Unique values                 |
| `dict`     | `{"name": "John"}` | Key-value data                |
| `NoneType` | `None`             | Represents no value           |

"""

num_int = 3;
print(f"num_int: {num_int}");

num_float = 3.5;
print(f"num_float: {num_float}");

num_complex = 5 + 3j;
print(f"num_complex: {num_complex}");

name = "ayush";
print(f"str: {name}");

result = True;
print(f"bool result: {result}");

