# Break Statement:

for i in range(1,22):
    if i == 11:
        break; #break statement break out of the loop if a condition is met.
    print(f"value of i: {i}");


# Continue statement:

for j in range(1,22):
    if(j == 11):
        continue; #continue does not execute that particular iteration and skips it.
    print(f"value of j: {j}");


