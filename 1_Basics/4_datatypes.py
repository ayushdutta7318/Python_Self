# Datatype:

"""
| Data Type  | Example    | Description           |
| ---------- | ---------- | --------------------- |
| `int`      | `25`       | Whole numbers         |
| `float`    | `25.75`    | Decimal numbers       |
| `str`      | `"Python"` | Text                  |
| `bool`     | `True`     | Boolean values        |
| `complex`  | `3 + 4j`   | Complex numbers       |
| `NoneType` | `None`     | Represents "no value" |

"""

n = 3 + 4j;
print(f"n: {n}, type: {type(n)}");